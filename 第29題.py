# ==========================================
# 1. 建立英文字母與兩位數代號對照字典
# ==========================================
codes = {
    'A': 10, 'B': 11, 'C': 12, 'D': 13, 'E': 14, 'F': 15, 'G': 16, 'H': 17,
    'J': 18, 'K': 19, 'L': 20, 'M': 21, 'N': 22, 'P': 23, 'Q': 24, 'R': 25,
    'S': 26, 'T': 27, 'U': 28, 'V': 29, 'X': 30, 'Y': 31, 'W': 32, 'Z': 33,
    'I': 34, 'O': 35
}

# ==========================================
# 2. 讀取身分證字號字串
# ==========================================
s = input().strip()

# ==========================================
# 3. 性別碼檢查與檢查碼計算
# ==========================================
# 檢查第二碼性別是否為 '1'（男）或 '2'（女）
if s[1] in ['1', '2']:
    # 查詢首碼英文字母的代號，並拆解十位數 X1 與個位數 X2
    num = codes[s[0]]
    X1 = num // 10
    X2 = num % 10
    
    # 依公式計算加權總和 P
    P = (X1 + 9 * X2 
         + 8 * int(s[1]) + 7 * int(s[2]) + 6 * int(s[3]) 
         + 5 * int(s[4]) + 4 * int(s[5]) + 3 * int(s[6]) 
         + 2 * int(s[7]) + int(s[8]) + int(s[9]))
    
    # 檢查 P 是否能被 10 整除
    if P % 10 == 0:
        print("CORRECT!!!")
    else:
        print("WRONG!!!")
else:
    # 性別碼不合規格，直接判定錯誤
    print("WRONG!!!")