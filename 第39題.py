# ==========================================
# 1. 讀取測試資料筆數
# ==========================================
n = int(input())

# ==========================================
# 2. 逐組讀取成績並判斷測驗結果
# ==========================================
for i in range(n):
    # 讀取單行三個科目的分數，並轉換為整數清單
    scores = list(map(int, input().split()))

    # 計算該名學生的 3 科總分
    total = sum(scores)

    # 統計不及格（< 60 分）的科目數量
    fail_count = len([s for s in scores if s < 60])

    # ==========================================
    # 3. 依據不及格科數進行多分支條件判斷
    # ==========================================
    # 情況 A：0 科不及格（3 科皆及格） -> 通過
    if fail_count == 0:
        print("P")

    # 情況 B：恰好 1 科不及格
    elif fail_count == 1:
        # 若總分達標（>= 220）則通過，否則獲得補考資格
        if total >= 220:
            print("P")
        else:
            print("M")

    # 情況 C：恰好 2 科不及格
    elif fail_count == 2:
        # 若剩下的及格科目成績特高（>= 80）則獲得補考，否則不通過
        if max(scores) >= 80:
            print("M")
        else:
            print("F")

    # 情況 D：3 科皆不及格 -> 無法通過
    else:
        print("F")