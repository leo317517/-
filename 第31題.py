# ==========================================
# 1. 持續讀取多筆測試資料直到輸入結束（EOF）
# ==========================================
while True:
    try:
        # 讀取一行整數序列，轉為整數清單並取得總長度 N
        nums = list(map(int, input().split()))
        n = len(nums)
        
        # 記錄是否已找到過半元素的旗標
        found = False
        
        # ==========================================
        # 2. 透過集合去重，統計各不重複數字出現頻率
        # ==========================================
        for x in set(nums):
            # 判斷出現次數是否嚴格大於總長度的一半 (N / 2)
            if nums.count(x) > n / 2:
                print(x)
                found = True
                break  # 過半元素至多只有一個，找到後立即結束檢查
        
        # ==========================================
        # 3. 若所有數字皆未達門檻，輸出 "NO"
        # ==========================================
        if not found:
            print("NO")

    except EOFError:
        # 遇到測資結束時安全跳出
        break