# ==========================================
# 1. 讀取開獎號碼與發票張數
# ==========================================
# 讀取 1 組特獎號碼（保持字串型態，避免遺失開頭的 0）
special = input()

# 依序讀取 3 組頭獎號碼，存入清單中
head_prizes = []
for _ in range(3):
    head_prizes.append(input())

# 讀取欲對獎的發票總張數 N
n = int(input())

# ==========================================
# 2. 初始化統計變數與獎金對照表
# ==========================================
# counts: 記錄 7 個獎項 的中獎張數（特獎、頭獎、二獎、三獎、四獎、五獎、六獎）
counts = [0] * 7

# prizes: 對應 7 個獎項 的中獎金額
prizes = [2000000, 200000, 40000, 10000, 4000, 1000, 200]

# 累計總中獎金額
total_money = 0

# ==========================================
# 3. 逐張比對發票並計算獎金
# ==========================================
for _ in range(n):
    ticket = input()

    # (A) 先檢查是否對中特獎（8 碼全中）
    if ticket == special:
        counts[0] += 1
        total_money += prizes[0]

    # (B) 若非特獎，依序檢查頭獎～六獎（末 8 碼比對至末 3 碼）
    else:
        matched = False  # 標記該張發票是否已中獎

        # 由大獎至小獎比對長度：8, 7, 6, 5, 4, 3
        for length in range(8, 2, -1):
            for h in head_prizes:
                # 切片取出倒數 length 碼進行比對
                if ticket[-length:] == h[-length:]:
                    idx = 9 - length  # 計算獎項對應索引（頭獎: 1, ..., 六獎: 6）
                    counts[idx] += 1  # 累加該獎項張數
                    total_money += prizes[idx]  # 累加該獎項金額
                    matched = True  # 標記已中獎
                    break  # 跳出比對 3 組頭獎的迴圈

            # 若已符合較大獎項，立即跳出長度迴圈（避免重複領取較小獎項）
            if matched:
                break

# ==========================================
# 4. 格式化輸出結果
# ==========================================
# 輸出 7 個獎項張數，數字間以空格隔開
print(*counts)

# 換行輸出總中獎金額
print(total_money)