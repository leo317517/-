# ==========================================
# 1. 建立每月後半段切分日與對應星座清單
# ==========================================
# 各月後半段星座的起始日（1月至12月）
cutoffs = (21, 19, 21, 21, 22, 22, 23, 24, 24, 24, 23, 22)

# 各月份後半段對應的星座名稱
# 索引 0 為 1 月後半（Aquarius），最後一個為 12 月後半（Capricorn）
signs = (
    "Aquarius", "Pisces", "Aries", "Taurus", "Gemini", "Cancer",
    "Leo", "Virgo", "Libra", "Scorpio", "Sagittarius", "Capricorn"
)

# ==========================================
# 2. 持續讀取輸入直到測資結束（EOF 處理）
# ==========================================
while True:
    try:
        # 讀取單行的月份與日期
        month, day = map(int, input().split())

        # ==========================================
        # 3. 判斷星座並輸出
        # ==========================================
        # 若日期小於切分日，屬於上一個月份的星座（索引 month - 2）
        # 特別注意：當 month 為 1 時，1 - 2 = -1，Python 會精準對應至末端的 "Capricorn"
        if day < cutoffs[month - 1]:
            print(signs[month - 2])
        # 若日期大於等於切分日，屬於當月份後半段的星座（索引 month - 1）
        else:
            print(signs[month - 1])

    except EOFError:
        # 讀取到檔案/輸入結尾時安全跳出迴圈
        break